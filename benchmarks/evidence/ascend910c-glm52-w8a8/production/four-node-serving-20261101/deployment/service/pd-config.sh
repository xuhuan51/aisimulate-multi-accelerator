#!/usr/bin/env bash
# 用途：集中定义 GLM-5.2 Ascend 多 Prefill/多 Decode 服务的拓扑、镜像和推理参数。
#
# Prefill 格式：IP:HTTP端口:Bootstrap端口，多个节点用空格分隔。
# Decode 格式：IP:HTTP端口；每连续 DECODE_NNODES 个节点组成一个 Decode 实例。
# 示例：
#   PREFILL_NODES="10.0.0.11:8000:8998 10.0.0.12:8000:8998"
#   DECODE_NODES="10.0.0.21:8003 10.0.0.22:8003"

# ------------------------------ 服务拓扑 ------------------------------
PREFILL_NODES=${PREFILL_NODES:-"10.120.72.20:8000:8998 10.120.72.25:8000:8998"}
DECODE_NODES=${DECODE_NODES:-"10.120.72.31:8003 10.120.72.32:8003"}
DECODE_NNODES=${DECODE_NNODES:-2}
DECODE_DIST_PORT=${DECODE_DIST_PORT:-29500}

# 第一台 Prefill 默认兼任控制节点、Router 和 MemFabric Store。
_first_prefill_spec=${PREFILL_NODES%% *}
_default_primary_ip=${_first_prefill_spec%%:*}
ROUTER_IP=${ROUTER_IP:-$_default_primary_ip}
STORE_IP=${STORE_IP:-$_default_primary_ip}
ROUTER_PORT=${ROUTER_PORT:-6688}
STORE_PORT=${STORE_PORT:-24707}
unset _first_prefill_spec _default_primary_ip

# ------------------------------ SSH 与目录 ------------------------------
SSH_USER=${SSH_USER:-youxingye}
SSH_CONNECT_TIMEOUT=${SSH_CONNECT_TIMEOUT:-10}
SSH_IDENTITY_FILE=${SSH_IDENTITY_FILE:-/home/youxingye/.ssh/aisim_pd_ed25519}
REMOTE_SUDO=${REMOTE_SUDO:-1}
REMOTE_DIR=${REMOTE_DIR:-/home/youxingye/glm52-pd-aisim}

# ------------------------------ 镜像与模型 ------------------------------
IMAGE=${IMAGE:-quay.io/ascend/sglang@sha256:5f384cab0e16a4951ed0bdc54e1280f2108aeda6b8ede90ee527d8f4b5146443}
MODEL_DIR=${MODEL_DIR:-/data_lib/data/models/glm-q}
SERVED_MODEL_NAME=${SERVED_MODEL_NAME:-glm-5}
COMM_IFNAME=${COMM_IFNAME:-bond4}
HCCL_IF_BASE_PORT=${HCCL_IF_BASE_PORT:-50000}
PREFILL_HCCL_BUFFSIZE=${PREFILL_HCCL_BUFFSIZE:-650}
DECODE_HCCL_BUFFSIZE=${DECODE_HCCL_BUFFSIZE:-650}

# ------------------------------ 推理参数 ------------------------------
CONTEXT_LENGTH=${CONTEXT_LENGTH:-180000}
TP_SIZE=${TP_SIZE:-16}
DP_SIZE=${DP_SIZE:-4}
EP_SIZE=${EP_SIZE:-16}
PREFILL_TP_SIZE=${PREFILL_TP_SIZE:-16}
PREFILL_DP_SIZE=${PREFILL_DP_SIZE:-4}
PREFILL_EP_SIZE=${PREFILL_EP_SIZE:-16}
DECODE_TP_SIZE=${DECODE_TP_SIZE:-32}
DECODE_DP_SIZE=${DECODE_DP_SIZE:-32}
DECODE_EP_SIZE=${DECODE_EP_SIZE:-32}
NPU_DEVICE_COUNT=${NPU_DEVICE_COUNT:-16}
SHM_SIZE=${SHM_SIZE:-16g}
MEM_FRACTION_STATIC=${MEM_FRACTION_STATIC:-0.90}
PREFILL_MEM_FRACTION_STATIC=${PREFILL_MEM_FRACTION_STATIC:-0.88}
DECODE_MEM_FRACTION_STATIC=${DECODE_MEM_FRACTION_STATIC:-0.90}
PREFILL_MAX_RUNNING_REQUESTS=${PREFILL_MAX_RUNNING_REQUESTS:-128}
DECODE_MAX_RUNNING_REQUESTS=${DECODE_MAX_RUNNING_REQUESTS:-1024}
PREFILL_CHUNK_SIZE=${PREFILL_CHUNK_SIZE:-16384}
PREFILL_MAX_TOKENS=${PREFILL_MAX_TOKENS:-32768}
DECODE_GRAPH_MAX_BS=${DECODE_GRAPH_MAX_BS:-32}
DECODE_GRAPH_BATCHES=${DECODE_GRAPH_BATCHES:-"8 16 24 32"}
DISABLE_GRAPH=${DISABLE_GRAPH:-1}
DISABLE_OVERLAP=${DISABLE_OVERLAP:-1}
DISABLE_PREFIX_CACHE=${DISABLE_PREFIX_CACHE:-1}
ENABLE_SPECULATIVE_DECODING=${ENABLE_SPECULATIVE_DECODING:-0}
KV_PAGE_SIZE=${KV_PAGE_SIZE:-128}
DECODE_RESERVED_TOKENS=${DECODE_RESERVED_TOKENS:-512}

# ------------------------------ 管理参数 ------------------------------
PREFILL_CONTAINER_PREFIX=${PREFILL_CONTAINER_PREFIX:-glm52-aisim-eager-prefill}
DECODE_CONTAINER_PREFIX=${DECODE_CONTAINER_PREFIX:-glm52-aisim-eager-decode}
ROUTER_CONTAINER=${ROUTER_CONTAINER:-glm52-aisim-eager-router}
HEALTH_TIMEOUT=${HEALTH_TIMEOUT:-1800}
STORE_TIMEOUT=${STORE_TIMEOUT:-900}
PD_BOOTSTRAP_TIMEOUT=${PD_BOOTSTRAP_TIMEOUT:-600}
ROUTER_REQUEST_TIMEOUT=${ROUTER_REQUEST_TIMEOUT:-1800}
ENABLE_SYSTEM_TUNING=${ENABLE_SYSTEM_TUNING:-0}
# 仅在需要调用 /start_profile 时设为 1；修改后必须重启 Worker。
SGLANG_NPU_PROFILING=${SGLANG_NPU_PROFILING:-0}

export PREFILL_NODES DECODE_NODES ROUTER_IP STORE_IP ROUTER_PORT STORE_PORT
export SSH_USER SSH_CONNECT_TIMEOUT REMOTE_DIR IMAGE MODEL_DIR SERVED_MODEL_NAME
export COMM_IFNAME HCCL_IF_BASE_PORT CONTEXT_LENGTH TP_SIZE DP_SIZE EP_SIZE
export NPU_DEVICE_COUNT SHM_SIZE MEM_FRACTION_STATIC
export PREFILL_MAX_RUNNING_REQUESTS DECODE_MAX_RUNNING_REQUESTS
export PREFILL_CHUNK_SIZE PREFILL_MAX_TOKENS DECODE_GRAPH_MAX_BS DECODE_GRAPH_BATCHES
export PREFILL_CONTAINER_PREFIX DECODE_CONTAINER_PREFIX ROUTER_CONTAINER
export HEALTH_TIMEOUT STORE_TIMEOUT ENABLE_SYSTEM_TUNING
export PD_BOOTSTRAP_TIMEOUT ROUTER_REQUEST_TIMEOUT
export SGLANG_NPU_PROFILING
export DECODE_NNODES DECODE_DIST_PORT REMOTE_SUDO
export SSH_IDENTITY_FILE
export PREFILL_TP_SIZE PREFILL_DP_SIZE PREFILL_EP_SIZE DECODE_TP_SIZE DECODE_DP_SIZE DECODE_EP_SIZE
export PREFILL_MEM_FRACTION_STATIC DECODE_MEM_FRACTION_STATIC
export DISABLE_GRAPH DISABLE_OVERLAP DISABLE_PREFIX_CACHE ENABLE_SPECULATIVE_DECODING
export KV_PAGE_SIZE DECODE_RESERVED_TOKENS
export PREFILL_HCCL_BUFFSIZE DECODE_HCCL_BUFFSIZE
